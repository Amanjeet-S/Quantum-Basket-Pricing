"""Independent retained-field check of the smoothing-first amendment.

The new amendment producer and its mapping function are not imported.
Intrinsic exponential errors, normal discrepancies and the proof-derived
error formula are recomputed directly from retained exact rational fields.
The retained scale emitter is imported only to cross-check its coefficient
pair against a separately calculated pair. No circuit or QPE charge is
regenerated by this script; those have their separate retained audits.
"""
from pathlib import Path
from fractions import Fraction as F
import argparse
import gzip
import hashlib
import json
import sys

sys.dont_write_bytecode = True


def read(path):
    path = Path(path)
    if path.suffix == '.gz':
        with gzip.open(path, 'rt') as stream:
            return json.load(stream)
    return json.loads(path.read_text())


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def digest(value):
    return hashlib.sha256(json.dumps(
        value, sort_keys=True, separators=(',', ':'), default=str
    ).encode()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--repo', required=True)
    parser.add_argument('--raw-results', required=True)
    parser.add_argument('--smoothing-results', required=True)
    parser.add_argument('--amendment-source', required=True)
    parser.add_argument('--proof', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    repo = Path(args.repo).resolve()
    raw = Path(args.raw_results).resolve()
    smoothing = Path(args.smoothing_results).resolve()
    output = Path(args.output).resolve()
    if output.exists():
        raise FileExistsError('Preserve an earlier independent check')
    sys.path.insert(0, str(repo))
    from integral_value_oracle import scale_integer

    inputs = {
        'raw_resources': raw/'raw_payoff_resources.json.gz',
        'scalar_archive': raw/'raw_payoff_scalar_ordinates.json.gz',
        'raw_protocol': raw/'raw_payoff_protocol.json',
        'amended_resources': smoothing/'raw_payoff_smoothing_resources.json',
        'amended_protocol': smoothing/'raw_payoff_smoothing_protocol.json',
        'amendment_source': Path(args.amendment_source).resolve(),
        'checked_proof': Path(args.proof).resolve(),
        'gaussian_norms': repo/'results/gaussian_derivative_norms.json',
        'retained_scale_emitter': repo/'integral_value_oracle.py',
        'numerical_resources': repo/'results/strengthened_r1_resources.json',
        'threshold_resources': repo/'results/shared_threshold_resources.json',
    }
    hashes_before = {name: sha(path) for name, path in inputs.items()}
    old = read(inputs['raw_resources'])
    ordinates = read(inputs['scalar_archive'])
    new = read(inputs['amended_resources'])
    protocol = read(inputs['amended_protocol'])
    assert new['protocol_sha256'] == hashes_before['amended_protocol']
    assert new['base_resources_sha256'] == hashes_before['raw_resources']
    assert new['base_archive_sha256'] == hashes_before['scalar_archive']
    assert new['amendment_source_sha256'] == hashes_before['amendment_source']
    assert new['checked_smoothing_proof_sha256'] == hashes_before['checked_proof']
    assert new['numerical_resources_sha256'] == hashes_before['numerical_resources']
    assert new['threshold_resources_sha256'] == hashes_before['threshold_resources']
    nu0 = F(next(row['norm_upper'] for row in read(inputs['gaussian_norms'])['unit_norms']
                 if row['unit_derivative_order'] == 0 and row['passed']))

    exp, normal = {}, {}
    for entry in ordinates:
        cert = entry['certificate']
        if (cert.get('name') == 'exp' and F(cert['lo']) == 0
                and F(cert['span']) == F(1, 64)):
            key = (cert['table_bits'], cert['q'])
            if key in exp:
                assert exp[key] == cert
            exp[key] = cert
        if cert.get('schema') == 'qbp-integral-quantile-v1':
            key = (cert['b_y'], cert['q'], F(cert['L']))
            if key in normal:
                assert normal[key] == cert
            normal[key] = cert

    assert len(old['records']) == len(new['records']) == 48
    assert len(protocol['fixed_circuit_pool']) == 48
    selected_smoothing, row_checks = 0, []
    for base, amended, binding in zip(
            old['records'], new['records'], protocol['fixed_circuit_pool']):
        assert amended['model_id'] == base['original_model_id']
        assert amended['normal_bits'] == base['normal_bits']
        assert amended['exp_bits'] == base['payoff_exp_bits']
        assert all(amended[key] == value for key, value in binding.items())
        assert digest(base['graph_nodes']) == binding['graph_sha256']
        assert digest(base['profiles']) == binding['profile_sha256']
        assert digest(base['graph_configuration']) == binding['configuration_sha256']
        assert digest(base) == amended['retained_pointwise_row_sha256']
        graph = {node['name']: node for node in base['graph_nodes']}
        semantics = base['graph_semantic_nodes']
        body = {node['node']: node for node in
                base['probability_certificate']['body_arithmetic_certificate']['nodes']}
        q = base['graph_configuration']['q']
        scale = 2**q
        L = F(base['graph_configuration']['inner_normal_L'])
        lam = F(base['model']['lambda'])
        assert lam > 0

        # Calculate the emitter coefficient directly from rational arithmetic.
        if lam.denominator & (lam.denominator-1) == 0:
            integer = lam.numerator
            drop = lam.denominator.bit_length()-1
        else:
            nearest = lam*scale + F(1, 2)
            integer = nearest.numerator//nearest.denominator
            drop = q
        assert (integer, drop) == scale_integer(lam, q)
        E_s = 2*L*abs(F(integer, 2**drop)-lam)
        if drop > 0:
            E_s += F(1, scale)

        lower = graph[semantics['lower_endpoint']]
        assert lower['kind'] == 'add'
        inner_scale = graph[lower['args'][1]]
        assert inner_scale['kind'] == 'scale'
        assert F(inner_scale['meta']) == lam
        assert inner_scale['args'] == [semantics['normal_plus_L']]
        offset_add = graph[lower['args'][0]]
        assert offset_add['kind'] == 'add'
        assert offset_add['args'][0] == semantics['mG_offset']
        constant = graph[offset_add['args'][1]]
        offset = graph[semantics['common_offset']]
        assert constant['kind'] == offset['kind'] == 'constant'

        def error(name):
            return F(body[name]['absolute_output_error_upper'])

        E_m = (error(semantics['mG_offset'])
               + error(constant['name']) + error(offset['name']))
        e_delta = error(semantics['logT'])
        for node in (constant, offset):
            exact = F(node['meta'])
            rounded = exact*scale+F(1, 2)
            decoded = F(rounded.numerator//rounded.denominator, scale)
            assert error(node['name']) == abs(decoded-exact)

        # Reconstruct the intrinsic scalar error, rather than reusing the
        # graph's argument-perturbation-inclusive function-node error.
        exp_total = F(0)
        for side in ('PG', 'PA'):
            node = graph[semantics[side+'_exp']]
            assert node['kind'] == 'function'
            meta = node['meta']
            assert meta['name'] == 'exp' and F(meta['lo']) == 0
            assert F(meta['span']) == F(1, 64)
            cert = exp[(node['bits'], q)]
            nodal = max(max(abs(F(n['integer'], scale)-F(n['lower'])),
                            abs(F(n['integer'], scale)-F(n['upper'])))
                        for n in cert['nodes'])
            interpolation = (F(cert['second_derivative_upper'])
                             * (F(cert['span'])/2**cert['table_bits'])**2/8)
            intrinsic = nodal+interpolation+F(1, scale)
            assert intrinsic == F(cert['output_error_upper'])
            assert nodal == F(cert['nodal_error_upper'])
            assert interpolation == F(cert['linear_interpolation_error_upper'])
            exp_total += intrinsic

        quantile = normal[(amended['normal_bits'], q, L)]
        labels = 2**amended['normal_bits']
        a = F(quantile['mass_interval']['lower_exact_fraction'])
        D_N = ((1-a)/2+a/F(2*labels)
               + nu0*F(quantile['maximum_node_error_upper']))
        assert D_N == F(base['probability_certificate']['inner_normal_CDF_error_upper'])
        smooth_arithmetic = 100*exp_total+202*E_s+nu0/lam*(2*E_m+e_delta)
        smooth = min(F(1), smooth_arithmetic+2*D_N)
        pointwise = F(base['probability_certificate']['probability_error_upper'])
        eta = min(smooth, pointwise)
        assert eta == F(amended['probability_certificate']['probability_error_upper'])
        terms = amended['probability_certificate']['smoothing_derivation']
        assert smooth == F(terms['smoothing_probability_error_upper'])
        assert smooth_arithmetic == F(terms['smoothing_arithmetic_error_upper'])
        assert E_s == F(terms['inner_scale_error_upper'])
        assert nu0/lam*(2*E_m+e_delta) == F(terms['smooth_outer_shift_contribution_upper'])
        if smooth < pointwise:
            selected_smoothing += 1

        budget = amended['complete_deterministic_budget']
        previous_budget = base['complete_deterministic_budget']
        for field in ('coefficient_radius_upper', 'financial_transfer_upper',
                      'external_factor_upper', 'external_factor_radius',
                      'coefficient_interval', 'mass_interval', 'external_factor_midpoint'):
            assert budget[field] == previous_budget[field]
        det = (F(previous_budget['coefficient_radius_upper'])
               + F(previous_budget['financial_transfer_upper'])
               + F(previous_budget['external_factor_upper'])*eta
               + F(previous_budget['external_factor_radius']))
        assert det == F(budget['total_deterministic_undiscounted_price_error_upper'])
        prior = amended['coefficient_informed_prior']
        previous_prior = base['coefficient_informed_prior']
        assert F(prior['probability_lower']) == max(
            F(0), F(previous_prior['finite_ideal_mean_lower'])-eta)
        assert F(prior['probability_upper']) == min(
            F(1), F(previous_prior['finite_ideal_mean_upper'])+eta)
        assert prior['previous_mean_information_sha256'] == previous_prior['previous_mean_information_sha256']
        admitted = [plan for plan in amended['strategies'] if plan['result']['kind']
                    in ('complete_quantum_resource_plan', 'deterministic_correction_prior')]
        assert admitted
        assert amended['selected_strategy'] == min(
            admitted, key=lambda plan: (plan['result']['T_count'], plan['architecture']))
        row_checks.append({
            'model_id': amended['model_id'],
            'normal_bits': amended['normal_bits'],
            'exp_bits': amended['exp_bits'],
            'selected_eta_exact': str(eta),
            'pointwise_eta_exact': str(pointwise),
            'smoothing_eta_exact': str(smooth),
            'deterministic_error_exact': str(det),
        })

    numerical = read(inputs['numerical_resources'])
    threshold = read(inputs['threshold_resources'])
    comparisons = []
    for comparison in new['selected_comparisons']:
        mid = comparison['model_id']
        cohort = [row for row in new['records'] if row['model_id'] == mid
                  and row.get('selected_strategy')]
        winner = min(cohort, key=lambda row: (
            row['selected_strategy']['result']['T_count'],
            row['normal_bits'], row['exp_bits']))
        raw_T = winner['selected_strategy']['result']['T_count']
        numerical_T = next(row for row in numerical['selected_comparisons']
                           if row['original_model_id'] == mid)['selected_numerical_strategy']['result']['T_count']
        threshold_T = next(row for row in threshold['rows']
                           if row['original_model_id'] == mid)['selected_strategy']['result']['T_count']
        strongest = min(raw_T, numerical_T)
        saving = F(strongest-threshold_T, strongest)
        family = 'raw_payoff' if raw_T < numerical_T else 'numerical_conditional_price'
        assert comparison['raw_T'] == raw_T
        assert comparison['strongest_registered_rival_T'] == strongest
        assert F(comparison['event_saving_against_strongest_exact']) == saving
        assert comparison['strongest_registered_rival'] == family
        assert comparison['selected_normal_bits'] == winner['normal_bits']
        assert comparison['selected_exp_bits'] == winner['exp_bits']
        comparisons.append({
            'model_id': mid,
            'raw_minimum_T': raw_T,
            'numerical_minimum_T': numerical_T,
            'shared_threshold_T': threshold_T,
            'strongest_registered_rival_T': strongest,
            'strongest_registered_rival': family,
            'selected_raw_normal_bits': winner['normal_bits'],
            'selected_raw_exp_bits': winner['exp_bits'],
            'selected_raw_architecture': winner['selected_strategy']['architecture'],
            'selected_raw_QPE_M': winner['selected_strategy']['result']['flags'][0]['plan']['M'],
            'event_saving_against_strongest_exact': str(saving),
            'event_saving_against_raw_exact': str(F(raw_T-threshold_T, raw_T)),
            'event_saving_per_cent_diagnostic': float(100*saving),
        })
    assert len(comparisons) == 4
    assert hashes_before == {name: sha(path) for name, path in inputs.items()}
    record = {
        'schema': 'qbp-raw-payoff-independent-smoothing-recomputation-v1',
        'status': 'passed',
        'research_record_date': '2026-10-10',
        'checker_source_sha256': sha(__file__),
        'input_sha256': hashes_before,
        'checked_configurations': len(row_checks),
        'independent_coefficient_pairs_checked': len(row_checks),
        'intrinsic_exp_decompositions_checked': 2*len(row_checks),
        'normal_discrepancies_recomputed': len(row_checks),
        'eta_minima_checked': len(row_checks),
        'budget_and_prior_recomputations': len(row_checks),
        'smoothing_selected_configurations': selected_smoothing,
        'within_configuration_architecture_minima_checked': len(row_checks),
        'cross_family_complete_cost_minima_checked': len(comparisons),
        'QPE_charge_replay_performed_here': False,
        'rows': row_checks,
        'selected_comparisons': comparisons,
        'independence': 'The amendment producer and mapping function are not imported. Exact rational fields and the frozen proof formula are recomputed directly. The original scale emitter is cross-checked against independently calculated coefficient pairs.',
        'unresolved_scope': [
            'All costs are retained sufficient logical resource caps under the frozen finite pool and both retained architectures.',
            'Every selected exp width remains the upper registered boundary ten. No global precision optimum is established.',
            'This checker does not replay full circuits or QPE charge formulae; those are covered by the separate retained resource audits.',
            'The optional exact-variation sharpening is excluded from this amendment.',
            'No theoretical priority, algorithmic superiority outside the finite comparison, physical quantum advantage or quantum price outcome is established.'
        ],
        'repository_writes': False,
        'commits_or_index_changes': False,
        'licensed_data_used': False,
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(record, indent=2)+'\n')
    print('Passed independent smoothing recomputation:', len(row_checks),
          'configurations and', len(comparisons), 'strongest-rival minima.')


if __name__ == '__main__':
    main()
